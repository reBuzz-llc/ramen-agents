"""The generated docs files, built from their one source each. Run it after editing README.md, FENCE.md or
llms.txt, and commit what it writes:

    python3 scripts/build_docs.py           # write the generated files
    python3 scripts/build_docs.py --check   # exit 1 when one is stale: this is the test

- llms-full.txt          README.md and FENCE.md in one file, every relative link made absolute
- docs/llms.txt          a copy of llms.txt, served at https://rebuzz-llc.github.io/ramen-agents/llms.txt
- docs/llms-full.txt     a copy of llms-full.txt, served next to it
- docs/_includes/jsonld.html  the landing page's JSON-LD: SoftwareApplication, and FAQPage from the README's FAQ word for word
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REPO = "https://github.com/reBuzz-llc/ramen-agents"
RAW = "https://raw.githubusercontent.com/reBuzz-llc/ramen-agents/main"
SITE = "https://rebuzz-llc.github.io/ramen-agents"
DESCRIPTION = ("An open-source, free AI agent team for a small business: it finds leads, researches the market and prices "
               "service packages, each with a ready-to-send email your team sends, on free model tiers, inside a fence "
               "enforced in code.")
LINK = re.compile(r"(\]\()([^)\s]+)(\))")


def absolute(target: str) -> str:
    """A link target as an absolute URL: docs/ files on the Pages site, other files as raw Markdown, README anchors on GitHub."""
    if re.match(r"^[a-z]+:", target):
        return target
    if target.startswith("#"):
        return REPO + target
    if target.startswith("docs/"):
        rest = target[len("docs/"):]
        return f"{SITE}/{rest[:-3] + '.html' if rest.endswith('.md') else rest}"
    return f"{RAW}/{target}"


def absolutize(md: str) -> str:
    return LINK.sub(lambda m: m.group(1) + absolute(m.group(2)) + m.group(3), md)


def llms_full() -> str:
    readme = re.sub(r" ?<!--.*?-->", "", (ROOT / "README.md").read_text(encoding="utf-8"), flags=re.S).strip()   # hidden notes stay out of the .txt
    fence = (ROOT / "FENCE.md").read_text(encoding="utf-8").strip()
    return (f"# ramen-agents: full text for language models\n\nThe README and FENCE.md of {REPO}, in one file. "
            f"Generated by scripts/build_docs.py; edit README.md or FENCE.md instead.\n\n---\n\n"
            + absolutize(readme) + "\n\n---\n\n" + absolutize(fence) + "\n")


def plain(md: str) -> str:
    """Markdown answer text as the words a reader sees: links keep their text, code marks and line breaks go."""
    text = re.sub(r"\[([^\]]+)\]\([^)]+\)", r"\1", md)
    text = text.replace("`", "").replace("**", "")
    return " ".join(text.split())


def faq() -> list[tuple[str, str]]:
    readme = (ROOT / "README.md").read_text(encoding="utf-8")
    body = readme.split("\n## FAQ\n", 1)[1].split("\n## ", 1)[0]
    return [(q.strip(), plain(a)) for q, a in re.findall(r"^### (.+?)\n\n(.+?)(?=\n### |\Z)", body, re.S | re.M)]


def jsonld() -> str:
    app = {"@context": "https://schema.org", "@type": "SoftwareApplication", "name": "ramen-agents",
           "description": DESCRIPTION, "url": SITE + "/", "applicationCategory": "BusinessApplication",
           "operatingSystem": "macOS", "license": "https://www.apache.org/licenses/LICENSE-2.0",
           "offers": {"@type": "Offer", "price": "0", "priceCurrency": "USD"}, "sameAs": [REPO],
           "author": {"@type": "Organization", "name": "ReBuzz LLC"}}
    page = {"@context": "https://schema.org", "@type": "FAQPage",
            "mainEntity": [{"@type": "Question", "name": q, "acceptedAnswer": {"@type": "Answer", "text": a}} for q, a in faq()]}
    out = ["<!-- Generated by scripts/build_docs.py from README.md: edit the README, then run it. -->"]
    for obj in (app, page):
        out.append('<script type="application/ld+json">\n' + json.dumps(obj, ensure_ascii=False, indent=1).replace("</", "<\\/") + "\n</script>")
    return "\n".join(out) + "\n"


def outputs() -> dict[Path, str]:
    full = llms_full()
    llms = (ROOT / "llms.txt").read_text(encoding="utf-8")
    return {ROOT / "llms-full.txt": full, ROOT / "docs" / "llms.txt": llms, ROOT / "docs" / "llms-full.txt": full,
            ROOT / "docs" / "_includes" / "jsonld.html": jsonld()}


def main(argv: list[str]) -> int:
    stale = [p for p, text in outputs().items() if not p.exists() or p.read_text(encoding="utf-8") != text]
    if "--check" in argv:
        for p in stale:
            print(f"stale: {p.relative_to(ROOT)} (run python3 scripts/build_docs.py)")
        return 1 if stale else 0
    for p, text in outputs().items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8")
    print(f"wrote {len(outputs())} files ({len(stale)} changed)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
